#!/usr/bin/env python
"""Train CenterLoc3D on SVLD-3D in Google Colab.

This is a small wrapper around the official CenterLoc3D code.  It keeps the
official model/dataset/loss, adds AMP, per-epoch checkpoints and resume so a
Colab session can be interrupted without losing progress.

Example (Colab):
  python /content/riset-carom/scripts/train_centerloc3d_colab.py \
    --repo /content/CenterLoc3D \
    --train-txt /content/CenterLoc3D/dataset/DATA2021_train.txt \
    --scene 0cam --epochs 20 --freeze-epochs 5 --batch 8 \
    --out /content/drive/MyDrive/centerloc3d

The dataset txt must be generated by CenterLoc3D/dataset/data2script.py.
Run this script from anywhere; it chdirs to <repo>/train so the relative
`../DATAdevkit/...` paths in the txt resolve.
"""

from __future__ import annotations

import argparse
import csv
import os
import sys
import time
from pathlib import Path

import numpy as np
import torch
import torch.optim as optim
from torch.utils.data import DataLoader

MEAN = [0.40789655, 0.44719303, 0.47026116]
STD = [0.2886383, 0.27408165, 0.27809834]


def num(x) -> float:
    """Log a loss component whether it is a float or a tensor with grad."""
    return float(x.detach()) if torch.is_tensor(x) else float(x)


def finite(x):
    """Replace NaN/Inf so one degenerate box cannot poison the whole step.

    The official iou term is built from detached numpy geometry; a single
    zero-area predicted box produces NaN there and, because it is added to the
    total loss, turns every gradient into NaN as well.
    """
    if torch.is_tensor(x):
        return torch.nan_to_num(x, nan=0.0, posinf=1e4, neginf=0.0)
    return x if np.isfinite(x) else 0.0


def parse_args():
    ap = argparse.ArgumentParser("CenterLoc3D Colab trainer")
    ap.add_argument("--repo", required=True, help="path to CenterLoc3D")
    ap.add_argument("--train-txt", required=True)
    ap.add_argument("--val-txt", default="")
    ap.add_argument("--scene", default="", help="filter image path, e.g. 0cam; empty = all")
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--freeze-epochs", type=int, default=5)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--num-workers", type=int, default=2)
    ap.add_argument("--out", required=True)
    ap.add_argument("--resume", default="")
    ap.add_argument("--amp", action="store_true")
    ap.add_argument("--max-iters", type=int, default=0, help="debug: stop after N train iters")
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    return ap.parse_args()


def filter_lines(lines, scene):
    if not scene:
        return lines
    key = scene.replace("centre", "center")
    return [ln for ln in lines if key in ln or key.replace("0cam", "cam0") in ln]


def _grad_scaler(enabled: bool):
    """torch.cuda.amp is deprecated on new PyTorch; prefer torch.amp."""
    try:
        return torch.amp.GradScaler("cuda", enabled=enabled)
    except Exception:
        return torch.cuda.amp.GradScaler(enabled=enabled)


def _autocast(enabled: bool):
    try:
        return torch.amp.autocast("cuda", enabled=enabled)
    except Exception:
        return torch.cuda.amp.autocast(enabled=enabled)


def main():
    args = parse_args()
    repo = Path(args.repo).resolve()
    os.chdir(repo / "train")
    sys.path.insert(0, str(repo))
    # Old CenterLoc3D code uses np.float, removed in NumPy 2.
    np.float = float

    from dataset.dataloader import Bbox3dDatasets, bbox3d_dataset_collate
    from nets.fpn import KeyPointDetection
    from utils.loss import focal_loss, reg_iou_loss, reg_l1_loss, reproject_l1_loss

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    device = torch.device(args.device)
    input_shape = (512, 512, 3)
    output_shape = (128, 128)

    lines = Path(args.train_txt).read_text(encoding="utf-8").splitlines()
    lines = [ln for ln in lines if ln.strip()]
    lines = filter_lines(lines, args.scene)
    missing = [ln for ln in lines if not Path(ln.split(" ")[0]).exists()]
    if missing:
        print(f"skip {len(missing)} lines whose image is not present")
        lines = [ln for ln in lines if Path(ln.split(" ")[0]).exists()]
    if not lines:
        raise SystemExit(f"no lines for scene={args.scene!r} in {args.train_txt}")
    print(f"train lines: {len(lines)} (scene={args.scene or 'all'})")

    if args.val_txt:
        val_lines = Path(args.val_txt).read_text(encoding="utf-8").splitlines()
        val_lines = [ln for ln in val_lines if ln.strip()]
        val_lines = filter_lines(val_lines, args.scene)
    else:
        rng = np.random.default_rng(10101)
        idx = rng.permutation(len(lines))
        n_val = max(1, int(len(lines) * 0.1))
        val_lines = [lines[i] for i in idx[:n_val]]
        lines = [lines[i] for i in idx[n_val:]]
    print(f"train/val: {len(lines)}/{len(val_lines)}")

    train_ds = Bbox3dDatasets(lines, input_shape, 3, True)
    val_ds = Bbox3dDatasets(val_lines, input_shape, 3, False)
    train_dl = DataLoader(
        train_ds, batch_size=args.batch, shuffle=True, num_workers=args.num_workers,
        pin_memory=True, drop_last=True, collate_fn=bbox3d_dataset_collate,
    )
    val_dl = DataLoader(
        val_ds, batch_size=args.batch, shuffle=False, num_workers=args.num_workers,
        pin_memory=True, drop_last=False, collate_fn=bbox3d_dataset_collate,
    )

    model = KeyPointDetection(
        model_name="resnet", model_index=2, num_classes=3, pretrained_weights=True
    ).to(device)
    optimizer = optim.Adam(model.parameters(), lr=args.lr, weight_decay=5e-4)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, factor=0.5, patience=3
    )
    use_amp = bool(args.amp) and device.type == "cuda"
    scaler = _grad_scaler(use_amp)

    start_epoch = 0
    best = float("inf")
    if args.resume:
        ckpt = torch.load(args.resume, map_location="cpu", weights_only=False)
        poisoned = [
            k
            for k, v in ckpt["state_dict"].items()
            if torch.is_tensor(v) and not torch.isfinite(v).all()
        ]
        if poisoned:
            print(
                f"checkpoint {args.resume} berisi NaN/Inf di {len(poisoned)} tensor; "
                "dilewati dan mulai dari awal",
                flush=True,
            )
        else:
            model.load_state_dict(ckpt["state_dict"])
            optimizer.load_state_dict(ckpt["optimizer"])
            start_epoch = int(ckpt.get("epoch", 0))
            best = float(ckpt.get("best", best))
            print(f"resumed {args.resume} at epoch {start_epoch}, best={best:.4f}")

    log_path = out / "train_log.csv"
    if not log_path.exists():
        with log_path.open("w", newline="", encoding="utf-8") as fh:
            csv.writer(fh).writerow(["epoch", "train_loss", "val_loss", "lr", "seconds"])

    def run_epoch(dl, train: bool):
        model.train(train)
        total = 0.0
        n = 0
        skipped = 0
        for it, batch in enumerate(dl):
            if args.max_iters and it >= args.max_iters:
                break
            batch = [
                torch.from_numpy(b).float().to(device, non_blocking=True)
                if isinstance(b, np.ndarray)
                else b.float().to(device, non_blocking=True)
                for b in batch
            ]
            (
                imgs, calibs, hms, centers, vertices, sizes,
                masks, perspectives, base_points, raw_ws, raw_hs,
            ) = batch
            if train:
                optimizer.zero_grad(set_to_none=True)
            with torch.set_grad_enabled(train):
                with _autocast(use_amp):
                    pred_hm, pred_center, pred_vertex, pred_size = model(imgs)
                    cls_loss = focal_loss(pred_hm, hms)
                    center_loss = reg_l1_loss(pred_center, centers, masks, index=2)
                    vertex_loss = 0.1 * reg_l1_loss(pred_vertex, vertices, masks, index=16)
                    size_loss = 0.1 * reg_l1_loss(pred_size, sizes, masks, index=3)
                    reproj_loss = finite(
                        0.1 * reproject_l1_loss(
                            pred_vertex, calibs, pred_size, masks, base_points,
                            16, perspectives, output_shape, input_shape, raw_hs, raw_ws,
                        )
                    )
                    iou_loss = finite(
                        reg_iou_loss(
                            "ciou", pred_vertex, vertices, masks, perspectives,
                            output_shape, input_shape, raw_hs, raw_ws,
                        )
                    )
                    if iou_loss > 1.0:
                        iou_loss = torch.log(iou_loss)
                    loss = cls_loss + center_loss + vertex_loss + size_loss + reproj_loss + iou_loss
                bad = not torch.isfinite(loss)
                if train and not bad:
                    scaler.scale(loss).backward()
                    scaler.unscale_(optimizer)
                    torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
                    scaler.step(optimizer)
                    scaler.update()
            if bad:
                skipped += 1
                if skipped <= 5:
                    print(f"  lewati batch {it}: loss NaN/Inf", flush=True)
                continue
            total += float(loss.item())
            n += 1
            if it % 20 == 0:
                print(
                    f"  it {it}/{len(dl)} loss={total/max(n,1):.4f} "
                    f"cls={num(cls_loss):.3f} size={num(size_loss):.3f} "
                    f"reproj={num(reproj_loss):.3f} iou={num(iou_loss):.3f}",
                    flush=True,
                )
        if skipped:
            print(f"  {skipped} batch dilewati (loss tidak hingga)", flush=True)
        return total / max(n, 1), skipped

    for epoch in range(start_epoch, args.epochs):
        t0 = time.time()
        if epoch < args.freeze_epochs:
            model.freeze_backbone()
        else:
            model.unfreeze_backbone()
        train_loss, train_skipped = run_epoch(train_dl, True)
        if len(val_ds):
            val_loss, val_skipped = run_epoch(val_dl, False)
        else:
            val_loss, val_skipped = float("nan"), 0
        metric = val_loss if np.isfinite(val_loss) else train_loss
        if np.isfinite(metric):
            scheduler.step(metric)
        elapsed = time.time() - t0
        lr = optimizer.param_groups[0]["lr"]
        print(
            f"epoch {epoch+1}/{args.epochs} train={train_loss:.4f} "
            f"val={val_loss:.4f} lr={lr:.2e} {elapsed:.0f}s "
            f"(dilewati {train_skipped}/{val_skipped})",
            flush=True,
        )
        with log_path.open("a", newline="", encoding="utf-8") as fh:
            csv.writer(fh).writerow([epoch + 1, train_loss, val_loss, lr, round(elapsed, 1)])

        if not (np.isfinite(train_loss) and np.isfinite(val_loss)):
            print(
                "  checkpoint tidak disimpan: loss tidak hingga (NaN/Inf)",
                flush=True,
            )
            if train_skipped == 0 and val_skipped == 0:
                # weights are already poisoned; nothing useful can be resumed
                raise SystemExit(
                    "training berhenti: loss NaN padahal tidak ada batch yang "
                    "dilewati. Mulai ulang dengan --resume none."
                )
            continue

        state = {
            "epoch": epoch + 1,
            "state_dict": model.state_dict(),
            "optimizer": optimizer.state_dict(),
            "best": best,
        }
        torch.save(state, out / "checkpoint_last.pth")
        if np.isfinite(val_loss) and val_loss < best:
            best = val_loss
            state["best"] = best
            torch.save(state, out / "checkpoint_best.pth")
        print(f"  saved {out/'checkpoint_last.pth'}", flush=True)


if __name__ == "__main__":
    main()
